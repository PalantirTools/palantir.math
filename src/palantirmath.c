
// EXTERNAL INCLUDES
#include <math.h>
// INTERNAL INCLUDES
#include "palantirmath.h"

// ************************************************************************************************
f32 clamp(f32 value, f32 min, f32 max)
{
	return min * (value < min) +
		max * (value > max) +
		value * (value >= min && value <= max);
}
// ************************************************************************************************
f32 step(const f32 t)
{
	if (t >= 0.5f) return 1.0f;
	return 0.0f;
}
// ************************************************************************************************
f32 lerp(f32 a, f32 b, f32 t)
{
	return a + (b - a) * t;
}
// ************************************************************************************************
f32 in_out_sine(const f32 t)
{
	return -0.5f * (cos(PI * t) - 1.0f);
}
// ************************************************************************************************
f32 in_out_sigmoid(f32 x) {
	return 3.0f * x * x - 2.0f * x * x * x;
}
// ************************************************************************************************
f32 in_out_sigmoid_smoother(f32 x) {
	return x * x * x * (x * (x * 6.0f - 15.0f) + 10.0f);
}
// ************************************************************************************************
f32 in_expo(f32 x)
{
	return (x == 0.0f) ? 0.0f : powf(2.0f, 10.0f * (x - 1.0f));
}
// ************************************************************************************************
f32 out_bounce(f32 x)
{
    const f32 n1 = 7.5625f;
    const f32 d1 = 2.75f;

    if (x < 1.0f / d1)
    {
        return n1 * x * x;
    }
    else if (x < 2.0f / d1)
    {
        x -= 1.5f / d1;
        return n1 * x * x + 0.75f;
    }
    else if (x < 2.5f / d1)
    {
        x -= 2.25f / d1;
        return n1 * x * x + 0.9375f;
    }
    else
    {
        x -= 2.625f / d1;
        return n1 * x * x + 0.984375f;
    }
}
// ************************************************************************************************
extern f32 in_bounce(f32 x)
{
	return 1.0f - out_bounce(1.0f - x);
}
// ************************************************************************************************
extern f32 inout_bounce(f32 x)
{
	if (x < 0.5f)
	{
		return (1.0f - out_bounce(1.0f - 2.0f * x)) * 0.5f;
	}
	else
	{
		return out_bounce(2.0f * x - 1.0f) * 0.5f + 0.5f;
	}
}
